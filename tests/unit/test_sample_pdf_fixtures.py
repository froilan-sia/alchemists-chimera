def _normalize_text(text: str) -> str:
    """Normalize PDF line and page whitespace without changing word order."""
    return " ".join(text.replace("\r\n", "\n").replace("\r", "\n").split())


def _extract_text(path: Path) -> tuple[PdfReader, str]:
    """Open a PDF strictly and return its reader and ordered page text."""
    reader = PdfReader(path, strict=True)
    extracted = "\n".join(page.extract_text() or "" for page in reader.pages)
    return reader, extracted


def _extract_bytes(payload: bytes) -> tuple[PdfReader, str]:
    """Open generated bytes strictly and return ordered page text."""
    reader = PdfReader(BytesIO(payload), strict=True)
    extracted = "\n".join(page.extract_text() or "" for page in reader.pages)
    return reader, extracted


def _sha256(path: Path) -> str:
    """Return a file's SHA-256 digest."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


@pytest.mark.parametrize("fixture", FIXTURES, ids=lambda item: item.filename)
def test_checked_in_fixtures_have_strict_structure_and_source_parity(
    fixture: FixtureMetadata,
):
    """Each replacement is a complete PDF containing its canonical source."""
    payload = fixture.pdf_path.read_bytes()
    source = fixture.source_path.read_text(encoding="utf-8")

    assert payload.startswith(b"%PDF-1.4")
    assert payload.rstrip().endswith(b"%%EOF")

    reader, extracted = _extract_text(fixture.pdf_path)
    assert len(reader.pages) >= 1
    assert _normalize_text(extracted)
    assert _normalize_text(extracted) == _normalize_text(source)
    assert all(marker in extracted for marker in fixture.markers)
    assert all(marker in extracted for marker in fixture.subject_markers)


@pytest.mark.parametrize("fixture", FIXTURES, ids=lambda item: item.filename)
def test_pdf_parser_contract_is_preserved_for_repaired_fixtures(
    fixture: FixtureMetadata,
):
    """The normal parser returns usable chunks and provenance metadata."""
    parser = PDFParser()
    chunks = parser.parse_pdf(fixture.pdf_path)
    reader, _ = _extract_text(fixture.pdf_path)
    total_pages = len(reader.pages)
    expected_fields = {
        "id",
        "text",
        "page_number",
        "chunk_index",
        "total_chunks",
        "metadata",
        "start_char",
        "end_char",
        "document_id",
        "document_name",
    }

    assert chunks
    for chunk in chunks:
        assert set(vars(chunk)) == expected_fields
        assert chunk.text.strip()
        assert 1 <= chunk.page_number <= total_pages
        assert chunk.chunk_index >= 0
        assert chunk.total_chunks >= 1
        assert chunk.id.endswith(
            f"-page{chunk.page_number:03d}-chunk{chunk.chunk_index:03d}"
        )
        assert chunk.document_name == fixture.filename
        assert chunk.document_id
        assert chunk.metadata["document_id"] == chunk.document_id
        assert chunk.metadata["document_name"] == fixture.filename
        assert chunk.metadata["total_pages"] == total_pages
        assert chunk.metadata["page_text_length"] > 0
        assert chunk.start_char >= 0
        assert chunk.end_char > chunk.start_char
        assert chunk.end_char <= chunk.metadata["page_text_length"]
        assert chunk.end_char - chunk.start_char == len(chunk.text)


@pytest.mark.parametrize("fixture", FIXTURES, ids=lambda item: item.filename)
def test_generation_is_byte_and_digest_deterministic(
    fixture: FixtureMetadata, tmp_path: Path
):
    """Unchanged canonical sources reproduce identical output bytes."""
    first_directory = tmp_path / "first"
    second_directory = tmp_path / "second"

    generate_fixtures(first_directory, source_directory=SOURCE_DIRECTORY)
    generate_fixtures(second_directory, source_directory=SOURCE_DIRECTORY)

    first = first_directory / fixture.filename
    second = second_directory / fixture.filename
    assert first.read_bytes() == second.read_bytes()
    assert _sha256(first) == _sha256(second)

    _, first_text = _extract_text(first)
    _, second_text = _extract_text(second)
    assert _normalize_text(first_text) == _normalize_text(second_text)


def _copy_sources(source_directory: Path) -> None:
    """Copy all canonical source bytes into a temporary local directory."""
    source_directory.mkdir()
    for fixture in FIXTURES:
        target = source_directory / fixture.source_filename
        target.write_bytes(fixture.source_path.read_bytes())


def test_changed_canonical_source_changes_digest_and_extracted_text(tmp_path: Path):
    """A local source edit changes both serialized bytes and extracted text."""
    baseline_sources = tmp_path / "baseline-sources"
    changed_sources = tmp_path / "changed-sources"
    _copy_sources(baseline_sources)
    _copy_sources(changed_sources)

    target = changed_sources / FIXTURES[0].source_filename
    target.write_bytes(target.read_bytes() + b"\nLOCAL_SOURCE_CHANGE_MARKER")

    baseline_output = tmp_path / "baseline-output"
    changed_output = tmp_path / "changed-output"
    generate_fixtures(baseline_output, source_directory=baseline_sources)
    generate_fixtures(changed_output, source_directory=changed_sources)

    baseline_pdf = baseline_output / FIXTURES[0].filename
    changed_pdf = changed_output / FIXTURES[0].filename
    assert _sha256(baseline_pdf) != _sha256(changed_pdf)
    _, baseline_text = _extract_text(baseline_pdf)
    _, changed_text = _extract_text(changed_pdf)
    assert _normalize_text(baseline_text) != _normalize_text(changed_text)
    assert "LOCAL_SOURCE_CHANGE_MARKER" in changed_text


_ESCAPABLE_WORDS = st.sampled_from(
    (
        "capital",
        "risk",
        "ratio",
        "(parentheses)",
        r"back\\slash",
        r"C:\\local\\source",
        "15%",
    )
)


@st.composite
def _source_documents(draw: st.DrawFn) -> str:
    """Generate local ASCII sources with escaping and page-boundary cases."""
    line_count = draw(
        st.sampled_from(
            (
                1,
                LINES_PER_PAGE - 1,
                LINES_PER_PAGE,
                LINES_PER_PAGE + 1,
                LINES_PER_PAGE * 2 + 1,
            )
        )
    )
    lines = draw(
        st.lists(
            st.one_of(
                st.just(""),
                st.lists(_ESCAPABLE_WORDS, min_size=1, max_size=5).map(" ".join),
            ),
            min_size=line_count,
            max_size=line_count,
        )
    )
    if not any(lines):
        lines[0] = "capital (ratio) " + r"back\\slash"
    return "\n".join(lines)


@given(source_text=_source_documents())
@settings(max_examples=20, deadline=None)
def test_generated_sources_preserve_escaping_and_page_boundaries(source_text: str):
    """Property: escaped text and page-order content survive serialization."""
    first_bytes = build_pdf(source_text)
    second_bytes = build_pdf(source_text)
    first_reader, first_text = _extract_bytes(first_bytes)
    second_reader, second_text = _extract_bytes(second_bytes)

    assert first_bytes == second_bytes
    assert len(first_reader.pages) == len(second_reader.pages)
    assert len(first_reader.pages) >= 1
    assert [
        _normalize_text(page.extract_text() or "") for page in first_reader.pages
    ] == [_normalize_text(page.extract_text() or "") for page in second_reader.pages]
    assert _normalize_text(first_text) == _normalize_text(source_text)


