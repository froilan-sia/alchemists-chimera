def test_generation_preserves_readme_parser_and_unrelated_fixture_artifacts(
    tmp_path: Path,
):
    """Generation targets only the three named PDFs and preserves repository files."""
    readme_before = README_PATH.read_bytes()
    parser_before = PARSER_PATH.read_bytes()
    unrelated_before = {
        path: path.read_bytes() for path in UNRELATED_PATHS if path.exists()
    }

    output_directory = tmp_path / "generated"
    generated = generate_fixtures(output_directory, source_directory=SOURCE_DIRECTORY)

    assert {path.name for path in generated} == set(FIXTURE_MAPPING)
    assert all(path.parent == output_directory for path in generated)
    assert README_PATH.read_bytes() == readme_before
    assert PARSER_PATH.read_bytes() == parser_before
    assert {path: path.read_bytes() for path in unrelated_before} == unrelated_before

    readme = README_PATH.read_text(encoding="utf-8")
    assert all(requirement in readme for requirement in README_REQUIREMENTS)
    assert PDFParser().parse_pdf(INPUT_DIRECTORY / "test_hkma_basel.pdf")


def test_focused_validation_is_local_only(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
):
    """Generation and validation work with common network boundaries disabled."""

    def deny_network(*args, **kwargs):
        raise AssertionError("fixture validation attempted network access")

    monkeypatch.setattr(socket, "socket", deny_network)
    monkeypatch.setattr(socket, "create_connection", deny_network)
    monkeypatch.setattr(urllib.request, "urlopen", deny_network)
    monkeypatch.setattr(http.client, "HTTPConnection", deny_network)
    monkeypatch.setattr(http.client, "HTTPSConnection", deny_network)

    generated = generate_fixtures(
        tmp_path / "offline", source_directory=SOURCE_DIRECTORY
    )
    for path in generated:
        reader, extracted = _extract_text(path)
        assert len(reader.pages) >= 1
        assert _normalize_text(extracted)
        assert PDFParser().parse_pdf(path)
